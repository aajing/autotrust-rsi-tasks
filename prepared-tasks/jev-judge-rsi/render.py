def png(lines):
    lines = [str(x).upper() for x in lines]
    if len(lines) > 30 or any(len(line) > 60 for line in lines):
        raise ValueError("UI panel bounds")
    width, height, scale = 768, 768, 2
    pixels = [bytearray([248, 250, 252] * width) for _ in range(height)]
    for row, line in enumerate(lines):
        for col, char in enumerate(line):
            for y, pattern in enumerate(FONT.get(char, FONT["?"]).split("/")):
                for x, bit in enumerate(pattern):
                    if bit == "1":
                        for dy in range(scale):
                            for dx in range(scale):
                                px, py = 24 + col * 12 + x * scale + dx, 24 + row * 24 + y * scale + dy
                                pixels[py][px*3:px*3+3] = bytes([15, 23, 42])
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xffffffff)
    raw = b"".join(b"\x00" + bytes(row) for row in pixels)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
